"""WSA-05 proposition-local evidence governance, never satisfaction or confidence.

Basis identifiers are exact, provider-namespaced identifiers, not publisher/domain names.
Structured lineage is supplied by acquisition, not generated by the origin assessor.
"""
from enum import Enum

from pydantic import Field
from app.contracts.immutability import GovernableModel as BaseModel


class DependencyState(str, Enum):
    SAME_BASIS = "SAME_BASIS"
    DERIVED_FROM = "DERIVED_FROM"
    SEPARATE_EVIDENTIARY_BASIS = "SEPARATE_EVIDENTIARY_BASIS"
    DEPENDENCY_UNKNOWN = "DEPENDENCY_UNKNOWN"


class CorroborationState(str, Enum):
    SINGLE_BASIS = "SINGLE_BASIS"
    DEPENDENT_MULTIPLE_DOCUMENTS = "DEPENDENT_MULTIPLE_DOCUMENTS"
    MULTIPLE_SEPARATE_BASES = "MULTIPLE_SEPARATE_BASES"
    MIXED = "MIXED"
    CONFLICTING_BASES = "CONFLICTING_BASES"
    DEPENDENCY_UNKNOWN = "DEPENDENCY_UNKNOWN"


class OriginLineage(BaseModel):
    """Closed-world lineage for THIS span's contribution, supplied by a provider.

    A basis ID must identify a record/article/observation, never just a wire service.
    A syndicated article with new analysis must put lineage only on derivative spans.
    """
    proposition_signature: str = ""  # required for use; metadata never applies globally
    basis_source_ids: list[str] = Field(default_factory=list)
    derived_from_basis_ids: list[str] = Field(default_factory=list)


class OriginRelation(BaseModel):
    proposition_id: str
    evidence_id: str
    related_evidence_id: str
    dependency_state: DependencyState
    basis_description: str = ""
    basis_source_ids: list[str] = Field(default_factory=list)
    method: str = "llm"  # deterministic | llm
    # Grounding receipts: finding ID -> exact excerpt of its bounded input.
    evidence_quotes: dict[str, str] = Field(default_factory=dict)


class CorroborationGroup(BaseModel):
    proposition_id: str
    member_evidence_ids: list[str] = Field(default_factory=list)
    basis_description: str = ""
    dependency_state: DependencyState = DependencyState.DEPENDENCY_UNKNOWN
    basis_source_ids: list[str] = Field(default_factory=list)


class PropositionOrigins(BaseModel):
    proposition_id: str
    proposition_signature: str
    proposition_statement: str = ""
    corroboration_state: CorroborationState = CorroborationState.DEPENDENCY_UNKNOWN
    dependency_unresolved: bool = True  # stays visible even when conflict overrides state
    groups: list[CorroborationGroup] = Field(default_factory=list)
    relations: list[OriginRelation] = Field(default_factory=list)
    limitations: list[str] = Field(default_factory=list)
    # Bounded telemetry retained in the evidence projection, not Shared Knowledge.
    assessed_evidence_ids: list[str] = Field(default_factory=list)
    deterministic_signals: list[dict[str, str]] = Field(default_factory=list)
    llm_proposal: dict = Field(default_factory=dict)
    validation_notes: list[str] = Field(default_factory=list)
